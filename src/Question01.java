// Q.1 Write a program to print MySirG 5 times on the screen.

public class Question01 {
    public static void main(String []args){
        int i,j=1,k=1;
        for(i=1;i<=5;i++){
            System.out.println("MYSIRG");
        }
        //using Do-While loop;
        do{
            System.out.println("shivam");
            j++;
        }while(j<=5);
        // using while loop;
        while(k<=5){
            System.out.println("vivek");
            k++;
        }

    }


}
